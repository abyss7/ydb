    // =========================================================================
    // Greedy two-layer CPU-time + min-ratio selector & real-PCH feedback
    // =========================================================================

    struct TModelParams {
        double Q = 0.1;
        // Minimum net saved CPU-seconds per 1 MB (1e6 bytes) of PCH.
        double MinRatio = 0.5;
        // Optional resident PCH cap in bytes; 0 = unbounded.
        double DiskBudgetBytes = 0.0;
        // Consumer AST deserialization cost per unit of PCH parse seconds.
        double LoadShare = 0.02;
        // Prior PCH build CPU-seconds per parse second for base and delta.
        double BaseBuildScale = 1.1;
        double DeltaBuildScale = 1.75;
        // Prior PCH bytes per header source byte.
        double PchBytesPerSourceByte = 6.2;
        int AnalysisJobs = 1;
    };

    struct TArtifactMetrics {
        uint64_t Bytes = 0;
        double BuildSec = 0.0;
    };

    // Key: (ClassId, SortedParentRoots, SortedOwnRoots).
    using TArtifactKey = std::tuple<int, std::vector<int>, std::vector<int>>;

    // Real compiler feedback accumulated across Select <-> Materialize iterations.
    struct TSelectorFeedback {
        // [classId][unitId]: 1 if root failed PCH compilation in this class.
        std::vector<std::vector<char>> BannedUnits;
        // [classId][unitId]: measured PCH bytes per source byte (0 = use prior).
        std::vector<std::vector<double>> UnitBytesScale;
        // [classId][unitId]: measured build CPU-sec per parse sec (0 = use prior).
        std::vector<std::vector<double>> UnitBuildScale;
        // Exact sizes and build times of already materialized PCH chains.
        std::map<TArtifactKey, TArtifactMetrics> KnownArtifacts;
    };

    struct TPchGroup {
        int Class = -1;
        // Index of base group in TPchLayout::Groups, or -1 for a root/base PCH.
        int Parent = -1;
        int RepresentativeFile = -1;
        // Root unit IDs injected into this PCH's header.
        std::vector<int> Roots;
        // Complete sorted unit closure (including Parent's units when Parent >= 0).
        std::vector<int> Units;
        // Filled from real `.pch` stat() / getrusage once materialized (estimated before).
        uint64_t ActualBytes = 0;
        double ActualBuildSec = 0.0;
        // Relative buildDir paths of generated headers read by Clang during PCH build.
        std::vector<std::string> GeneratedDeps;
    };

    struct TPchLayout {
        // Bases precede deltas (`Parent < int(groupIndex)`).
        std::vector<TPchGroup> Groups;
        // Per target in TAnalysisModel::Targets: group index or -1 (no PCH).
        std::vector<int> Assignment;
        // Per target decision reason for diagnostics.
        std::vector<std::string> Reasons;
    };

