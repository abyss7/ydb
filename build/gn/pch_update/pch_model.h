    // Strongly connected component of headers.
    struct THeaderUnit {
        // Spelled #include token (<...> or "...") if self-contained; empty otherwise.
        std::string Include;
        // Normalized header paths belonging to this SCC.
        std::vector<std::string> Headers;
        // Directly included child unit IDs (excluding self).
        std::vector<int> Children;
        // Sorted historical commit indices [0, Scenarios) touching this unit.
        std::vector<int> Changes;
        // Sorted target IDs in TAnalysisModel::Targets that CANNOT consume a PCH
        // containing this unit without forming a Ninja or GN dependency cycle.
        std::vector<int> ForbiddenTargets;
        // Typical single-pass parse CPU-seconds of this unit.
        double ParseSec = 0.0;
        // Summed header source file bytes in this unit (serialized once per PCH).
        double SourceBytes = 0.0;
        // True when isolated compilation needs no non-runtime project symbols.
        bool SafeLink = true;
        // True if generated by a build action or located under <out>/.
        bool Generated = false;
    };

    // Single C++ translation unit in the compilation database.
    struct TTuFile {
        // Object path relative to buildDir (e.g. obj/foo/bar.o).
        std::string Object;
        // Normalized source path (relative to root or <out>/...).
        std::string Source;
        // Source path as written in compile_commands.json (relative to buildDir).
        std::string RawSource;
        int Class = -1;
        int Target = -1;
        // False for untraced C++ objects (< MaxMissingTraces): checked in Preflight
        // and CheckDeployment, and charged PCH load cost, with zero parse savings.
        bool Traced = true;
        double CompileSec = 0.0;
        double FrontendSec = 0.0;
        double HeaderSec = 0.0;
        // Sorted historical commit indices [0, Scenarios) rebuilding this TU.
        std::vector<int> Changes;
        // Sorted (unitId, exclusiveOwnParseSec) pairs from the baseline trace.
        std::vector<std::pair<int, double>> Own;
    };

    // Atomic GN PCH assignment unit (`global_pch_owner`).
    struct TTargetOwner {
        std::string Label;
        // -1 if TUs of this owner have mixed compiler flag classes.
        int Class = -1;
        // True when all compiling subtargets hook into `global_pch_owner` and
        // the target is not a prerequisite of global PCH platform_deps.
        bool PchEligible = true;
        // Specific reason if ineligible (e.g. "no-global-pch-hook", "mixed-compiler-classes", "pch-platform-dep").
        std::string IneligibleReason;
        std::vector<int> Files;
    };

