#!/usr/bin/env python3
"""Generate the C source that registers all frozen Python modules.

Reads a JSON file with the list of frozen modules (the output of
list_stdlib_modules.py — array of {"name", "path", "package"} objects)
and emits a single C file. The file replaces the role of
contrib/tools/python3/Python/frozen.c for our bin/python3 target:
it #includes every per-module header produced by _freeze_module and
populates the three frozen tables (bootstrap / stdlib / test) plus
the alias table that CPython's import machinery consults.

The bootstrap table holds the three modules CPython requires before
its disk-backed import system is even set up:
    _frozen_importlib            — bytecode of importlib._bootstrap
    _frozen_importlib_external   — bytecode of importlib._bootstrap_external
    zipimport
These names are special in CPython internals (see Python/pylifecycle.c);
their canonical Python-visible names are wired up via aliases.
"""

import argparse
import json
import sys


# Modules that must live in _PyImport_FrozenBootstrap, not in the stdlib
# table. Keyed by dotted source name; value is the canonical bootstrap name
# CPython expects in the table.
BOOTSTRAP_RENAMES = {
    "importlib._bootstrap": "_frozen_importlib",
    "importlib._bootstrap_external": "_frozen_importlib_external",
    "zipimport": "zipimport",
}

# Aliases consulted by the frozen importer to translate a requested module
# name into the entry it should serve. Mirrors the upstream Python/frozen.c
# set, restricted to the entries that are relevant once test scaffolding is
# stripped out.
ALIASES = [
    ("_frozen_importlib", "importlib._bootstrap"),
    ("_frozen_importlib_external", "importlib._bootstrap_external"),
    ("os.path", "posixpath"),
]


def varname(module_name: str) -> str:
    """Match the symbol naming convention used by _freeze_module.c:get_varname."""
    return "_Py_M__" + module_name.replace(".", "_")


def c_string(s: str) -> str:
    # Module names contain only [A-Za-z0-9._], no escaping needed in practice.
    # We still defensively escape backslashes and double quotes.
    escaped = s.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def emit_entry(name: str, var: str, is_package: bool) -> str:
    pkg = "true" if is_package else "false"
    return (
        f"    {{{c_string(name)}, {var}, (int)sizeof({var}), {pkg}}},"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--list", required=True,
                        help="Path to JSON list of frozen modules")
    parser.add_argument("--output", required=True,
                        help="Path to write the generated .c file")
    args = parser.parse_args()

    with open(args.list, "r") as f:
        modules = json.load(f)

    # Split into bootstrap and stdlib buckets.
    bootstrap: list[tuple[str, str, bool]] = []  # (entry_name, varname, is_package)
    stdlib: list[tuple[str, str, bool]] = []
    seen_names: set[str] = set()

    for entry in modules:
        name = entry["name"]
        is_pkg = bool(entry["package"])
        if name in seen_names:
            print(f"duplicate module name: {name}", file=sys.stderr)
            return 1
        seen_names.add(name)

        var = varname(name)
        if name in BOOTSTRAP_RENAMES:
            bootstrap.append((BOOTSTRAP_RENAMES[name], var, is_pkg))
        else:
            stdlib.append((name, var, is_pkg))

    # CPython expects bootstrap_modules to be in a specific order: the two
    # importlib bootstraps first, zipimport last. Re-sort accordingly.
    bootstrap_order = {
        "_frozen_importlib": 0,
        "_frozen_importlib_external": 1,
        "zipimport": 2,
    }
    bootstrap.sort(key=lambda e: bootstrap_order.get(e[0], 99))

    # stdlib is already sorted by module name in the input JSON, but make
    # sure — header inclusion order should also be stable.
    stdlib.sort(key=lambda e: e[0])

    # Collect headers to include. Both buckets reference per-module headers
    # whose paths derive from the *source* dotted name, not the entry name.
    # Reconstruct that mapping by inverting BOOTSTRAP_RENAMES.
    source_names = sorted({e["name"] for e in modules})

    out = []
    out.append("/* Auto-generated by build/gn/scripts/gen_frozen_index.py. Do not edit. */\n")
    out.append("#include \"Python.h\"\n")
    out.append("#include \"pycore_import.h\"\n")
    out.append("\n")
    out.append("#include <stdbool.h>\n")
    out.append("\n")
    for name in source_names:
        out.append(f'#include "frozen_modules/{name}.h"\n')
    out.append("\n")

    out.append("static const struct _frozen bootstrap_modules[] = {\n")
    for name, var, is_pkg in bootstrap:
        out.append(emit_entry(name, var, is_pkg) + "\n")
    out.append("    {0, 0, 0} /* sentinel */\n")
    out.append("};\n\n")

    out.append("static const struct _frozen stdlib_modules[] = {\n")
    for name, var, is_pkg in stdlib:
        out.append(emit_entry(name, var, is_pkg) + "\n")
    out.append("    {0, 0, 0} /* sentinel */\n")
    out.append("};\n\n")

    out.append("static const struct _frozen test_modules[] = {\n")
    out.append("    {0, 0, 0} /* sentinel */\n")
    out.append("};\n\n")

    out.append("const struct _frozen *_PyImport_FrozenBootstrap = bootstrap_modules;\n")
    out.append("const struct _frozen *_PyImport_FrozenStdlib = stdlib_modules;\n")
    out.append("const struct _frozen *_PyImport_FrozenTest = test_modules;\n\n")

    out.append("static const struct _module_alias aliases[] = {\n")
    for alias_name, orig in ALIASES:
        out.append(f"    {{{c_string(alias_name)}, {c_string(orig)}}},\n")
    out.append("    {0, 0} /* sentinel */\n")
    out.append("};\n")
    out.append("const struct _module_alias *_PyImport_FrozenAliases = aliases;\n\n")

    # Embedding hook: kept NULL, matching upstream frozen.c. Apps can override.
    out.append("const struct _frozen *PyImport_FrozenModules = NULL;\n")

    with open(args.output, "w") as f:
        f.write("".join(out))

    return 0


if __name__ == "__main__":
    sys.exit(main())
